def tier(v):
    listed = [x for x in v if x != "-"]
    n = len(listed); nb = sum(1 for x in listed if x == "b")
    return ("K" if (n >= 3 and nb * 2 < n) else "B"), n, nb

def render(items):
    rows = []
    for iid, name, v, syn, note in items:
        t, n, nb = tier(v)
        src = " ".join(f"E{i+1}:{x}" for i, x in enumerate(v))
        rows.append((iid, name, t, n, nb, src, syn, note))
    return rows

